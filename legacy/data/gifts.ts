// Rarity follows power: tier 1 → ธรรมดา, tier 2 → ไม่ธรรมดา, tier 3 → มหากาพย์, with hand-picked หายาก/ตำนาน
const LEGENDARY = new Set(['b_destiny', 'b_phoenix', 'b_heroname', 'b_worldtree', 'b_youth', 'b_wings', 'b_saintmark', 'b_angel', 'b_fateweaver',
  'c_doomed', 'c_souldebt', 'c_heircurse', 'c_demoneye', 'c_disaster', 'c_lichseed']);
const RARE = new Set(['b_lightward', 'b_undeadslayer', 'b_curseward', 'b_insight', 'b_oracleear', 'b_quicklearn', 'b_goldhand', 'b_treasurenose',
  'b_beastlord', 'b_healerhands', 'b_raincaller', 'b_spiritfriend', 'b_sacredflame', 'b_truelove', 'b_secondchance', 'b_shadowstep', 'b_fury',
  'c_vampbite', 'c_moonfrenzy', 'c_lovedoom', 'c_cursedblood', 'c_evileye', 'c_betrayal', 'c_cassandra', 'c_chicken', 'c_rage']);
const rarityOf = (id: string, tier: number): Rarity => (LEGENDARY.has(id) ? 'L' : RARE.has(id) ? 'R' : tier === 3 ? 'E' : tier === 2 ? 'U' : 'C');

const toGift = (kind: Gift['kind']) => ([id, name, tier, fx, desc]: Row): Gift => ({
  id, name, tier, fx, desc, kind, tags: (fx.match(/#(\w+)/g) || []).map((s) => s.slice(1)), rarity: rarityOf(id, tier),
});
export const BLESSINGS: Gift[] = BLESS.map(toGift('blessing'));
export const CURSES: Gift[] = CURSE.map(toGift('curse'));
export const giftById = (id: string) => BLESSINGS.find((g) => g.id === id) || CURSES.find((g) => g.id === id)!;
