/** Miracle ids by the line they belong to (20-god-ui.md §7.1: create, destroy, dragon, fate); the table has no `line` column. */
export function lineOfMiracle(m: { id: string; tier?: string; cost: { faith?: number; dread?: number; faithAll?: boolean } }): 0 | 1 | 2 | 3 {
  if (m.id === 'MR-25') return 3;
  if (m.tier === 'มังกร') return 2;
  return m.cost.dread && !m.cost.faith && !m.cost.faithAll ? 1 : 0;
}
