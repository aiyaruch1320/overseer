// Writes src/art/scenery/countries.ts from data/gen/countries.json: the `ui` values of every country that the painter of town scenes reads
// (roofs, the styles by weight, tree, ambient, wall, centre, lamps) and the colours its `look.materials` names. Run: node scripts/tools/gen-scenery-countries.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('data/gen/countries.json', 'utf8'));
const rows = data.items.map((c) => {
  const u = c.ui, raw = u.raw;
  const styles = Object.entries(u.styles).sort((a, b) => b[1] - a[1]).map(([k]) => k).slice(0, 3);
  const mats = [...new Set((c.look.materials.match(/#[0-9a-fA-F]{6}/g) ?? []).map((h) => h.toLowerCase()))].slice(0, 5);
  const o = { roofs: u.roofs.map((h) => h.toLowerCase()), mats, styles, tree: raw.tree ?? '', ambient: u.ambient, wall: u.wall, centre: u.centre, lamps: raw.lamps === 'true' ? 1 : 0 };
  return `  '${c.id}': ${JSON.stringify(o).replace(/"([a-z]+)":/g, '$1:').replace(/"/g, "'")},`;
});
writeFileSync('src/art/scenery/countries.ts', `// GENERATED by scripts/tools/gen-scenery-countries.mjs from data/gen/countries.json (the \`ui\` of every country): do not edit by hand,
// tests/art/scenery.test.ts checks it against the data. The values the painter of town and indoor scenes reads for a country.
export interface CountryScenery {
  /** The roof colours of the country (\`roofs=\`); empty means the continent's own. */
  roofs: string[];
  /** The colours the \`materials\` text names, wall and timber first. */
  mats: string[];
  /** The house styles by weight, up to three (\`styles=\`). */
  styles: string[];
  /** \`tree=\`: oak palm cactus dead, or empty. */
  tree: string;
  /** \`ambient=\`: none fog smoke clouds dust embers gulls sand leaves motes ash. */
  ambient: string;
  /** \`wall=\`: none stone iron palisade hedge. */
  wall: string;
  /** \`centre=\`: none obelisk bonfire lighthouse lake gate forge oasis airship fountain gear clock crystal skynest. */
  centre: string;
  lamps: 0 | 1;
}

export const COUNTRIES: Record<string, CountryScenery> = {
${rows.join('\n')}
};
`);
console.log(`${rows.length} countries`);
