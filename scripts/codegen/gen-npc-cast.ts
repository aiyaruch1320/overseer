// Reads docs/lore/npcs/*.md and writes src/data/npcCast.ts: one short row per NPC (id, name, people, age, role, appearance chance).
// The look of each NPC is derived from that row by src/data/cast.ts, so the docs stay the single source of truth.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'docs/lore/npcs';
const rows: [string, string, string, string, string, number, string, string][] = [];
for (const f of readdirSync(dir).filter((x) => /^\d\d-.*\.md$/.test(x)).sort()) {
  for (const line of readFileSync(join(dir, f), 'utf8').split('\n')) {
    const m = line.match(/^\|\s*([A-Z]{2}\d{2}-\d+)\s*\|\s*\*\*(.+?)\*\*\s*(?:\(([^)]*)\))?\s*([^|]*)\|.*?\|\s*(\d+)%\s*\|?\s*$/);
    if (!m) continue;
    const [, id, name, paren = '', role, pct] = m;
    const [people, age = ''] = paren.split('·').map((x) => x.trim());
    // what the story says about where they came from: 'h' born at a named place, 'm' came from elsewhere (refugee, exile)
    const story = line.split('|')[3]?.trim() ?? '';
    const born = story.match(/^(เกิด(?:ที่|ใน|บน|นอก)[^ ]*(?: [^ ]+)?)/);
    const flag = born ? 'h' : /หนีจาก|ผู้ลี้ภัย|ผู้พลัดถิ่น|เนรเทศ|อพยพ|ไม่เคยกลับไปบ้านเกิด/.test(story) ? 'm' : '';
    rows.push([id, name.trim(), people || '', age, role.trim(), +pct, flag, flag === 'h' ? born![1] : '']);
  }
}
const out = `// Generated by scripts/codegen/gen-npc-cast.ts from docs/lore/npcs — do not edit by hand.\n// [id, name, people as the docs write it, age as the docs write it, role, chance of appearing %, birth flag, birth note]\nexport type CastRow = [string, string, string, string, string, number, string, string];\nexport const NPC_CAST: CastRow[] = [\n${rows.map((r) => '  ' + JSON.stringify(r)).join(',\n')},\n];\n`;
writeFileSync('src/data/npcCast.ts', out);
console.log(rows.length, 'npcs');
