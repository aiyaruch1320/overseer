// Reads docs/countries/*.md and writes src/data/countries.ts (the 143 documented countries, in doc order).
// Run again after editing the docs:  npx tsx scripts/gen-countries.ts
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = 'docs/countries';
const files = readdirSync(dir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort();
const out: Record<string, string | number>[] = [];
const field = (line: string, key: string) => {
  const m = line.match(new RegExp(`\\*\\*${key}:\\*\\*\\s*(.*?)(?:\\s+·\\s+\\*\\*|$)`));
  return m ? m[1].trim() : '';
};
files.forEach((f, ci) => {
  const lines = readFileSync(`${dir}/${f}`, 'utf8').split('\n');
  let cur: Record<string, string | number> | null = null;
  for (const l of lines) {
    const h = l.match(/^#### ([A-Z]{2}-\d\d) (\S+) — (.+)$/);
    if (h) { cur = { code: h[1], cont: ci, name: h[2], title: h[3], gov: '', races: '', religion: '', story: '', rel: '', hook: '' }; out.push(cur); continue; }
    if (!cur) continue;
    if (l.startsWith('- **รัฐ:**')) { cur.gov = field(l, 'รัฐ'); cur.races = field(l, 'เผ่า'); cur.religion = field(l, 'ศาสนา'); }
    else if (l.startsWith('- **เรื่องราว:**')) cur.story = l.replace('- **เรื่องราว:**', '').trim();
    else if (l.startsWith('- **ความสัมพันธ์:**')) cur.rel = l.replace('- **ความสัมพันธ์:**', '').trim();
    else if (l.startsWith('- **ปมเรื่องหลัก:**')) cur.hook = l.replace('- **ปมเรื่องหลัก:**', '').trim();
  }
});
const body = out.map((c) => `  ${JSON.stringify(c)},`).join('\n');
writeFileSync('src/data/countries.ts', `// GENERATED by scripts/gen-countries.ts from docs/countries/*.md — do not edit by hand.
export interface CountryDoc { code: string; cont: number; name: string; title: string; gov: string; races: string; religion: string; story: string; rel: string; hook: string }
export const COUNTRY_DOCS: CountryDoc[] = [
${body}
];
`);
console.log(out.length, 'countries');
