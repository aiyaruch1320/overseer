// Reads the birthplace tables of docs/systems/character/01-origin.md (home lands of each people, and where the parents of a half-blood meet)
// and writes src/data/birthTables.ts, so the birth of every NPC follows the docs and the docs stay the single source of truth.
import { readFileSync, writeFileSync } from 'node:fs';

const RACES: [string, string][] = [
  ['ดาร์กเอลฟ์', 'darkelf'], ['เอลฟ์', 'elf'], ['มนุษย์', 'human'], ['คนแคระ', 'dwarf'], ['ออร์ค', 'orc'], ['ฮาล์ฟลิง', 'halfling'], ['เผ่าสัตว์', 'beast'], ['นาคา', 'naga'],
  ['เผ่ามังกร', 'dragonkin'], ['แวมไพร์', 'vampire'], ['ภูตพราย', 'fae'], ['สไลม์', 'slime'], ['เผ่าปีศาจ', 'demonkin'], ['เงือก', 'merfolk'], ['เผ่าปีก', 'winged'], ['ยักษ์', 'giant'],
  ['เผ่าลาวา', 'lavakin'], ['ลูกผสมจักรกล', 'construct'], ['หุ่นวิญญาณ', 'soulmachine'], ['มัมมี่', 'mummy'], ['กูล', 'ghoul'],
];
const raceOf = (s: string) => RACES.find(([n]) => s.startsWith(n));

/** "AL-01 ถึง AL-28", "SH-07 SH-15", "เมืองใหญ่ทั่วโลก" -> codes */
function codes(s: string): string[] {
  const out: string[] = [];
  const re = /([A-Z]{2})-(\d\d)(?:\s*ถึง\s*(?:([A-Z]{2})-)?(\d\d))?/g;
  for (let m; (m = re.exec(s)); ) {
    const a = +m[2], b = m[4] ? +m[4] : a;
    for (let i = a; i <= b; i++) out.push(`${m[1]}-${String(i).padStart(2, '0')}`);
  }
  if (/เมืองใหญ่/.test(s)) out.push('BIG');
  return out;
}

const lines = readFileSync('docs/systems/character/01-origin.md', 'utf8').split('\n');
const homes: Record<string, { main: string[]; mainPct: number; dia: string[]; diaPct: number }> = {};
const pairs: { a: string; b: string; meet: [string, number][]; mains: string[]; note: string }[] = [];
let mode = '';
for (const line of lines) {
  if (/^## 3\./.test(line)) mode = 'home';
  else if (/^## 4\./.test(line)) mode = 'four';
  else if (/^\*\*ตารางถิ่นพบกัน/.test(line)) mode = 'pair';
  else if (/^\*\*ผลของเหตุ/.test(line) || /^## 5\./.test(line)) mode = '';
  if (!line.startsWith('|')) continue;
  const c = line.split('|').slice(1, -1).map((x) => x.trim());
  if (mode === 'home' && c.length >= 7) {
    const r = raceOf(c[0]);
    if (r && r[0] === c[0]) homes[r[1]] = { main: codes(c[1]), mainPct: +c[2], dia: codes(c[3]), diaPct: +c[4] };
  } else if (mode === 'pair' && c.length >= 3) {
    const ra = raceOf(c[0]); if (!ra) continue;
    const rb = raceOf(c[0].slice(ra[0].length).trim()); if (!rb) continue;
    const meet: [string, number][] = [];
    for (const m of c[1].matchAll(/([A-Z]{2}-\d\d)(?:\s*ถึง\s*(?:[A-Z]{2}-)?(\d\d))?\s+(\d+)/g)) {
      const list = codes(m[2] ? `${m[1]} ถึง ${m[2]}` : m[1]);
      for (const code of list) meet.push([code, +m[3] / list.length]);
    }
    pairs.push({ a: ra[1], b: rb[1], meet, mains: codes(c[2]), note: c[2].replace(/^[A-Z]{2}-\d\d(?:\s*(?:ถึง\s*)?(?:[A-Z]{2}-)?\d\d)*\s*/, '').replace(/^—$/, '') });
  }
}
const out = `// Generated by scripts/gen-birth.ts from docs/systems/character/01-origin.md (หัวข้อ 3 และ 4) — do not edit by hand.
export const HOMES: Record<string, { main: string[]; mainPct: number; dia: string[]; diaPct: number }> = ${JSON.stringify(homes)};
/** where the parents of a half-blood meet: [meeting lands with weights], [home lands that need a special reason], the reason */
export const PAIRS: { a: string; b: string; meet: [string, number][]; mains: string[]; note: string }[] = ${JSON.stringify(pairs)};
`;
writeFileSync('src/data/birthTables.ts', out);
